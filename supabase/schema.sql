-- Electrify Mobility: Supabase Database Schema

-- 1. Stations table
CREATE TABLE IF NOT EXISTS public.stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  address TEXT NOT NULL,
  operator TEXT NOT NULL,
  region TEXT NOT NULL,
  type TEXT NOT NULL, -- 'DC_FAST' or 'AC_SLOW'
  price TEXT,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Reports table
CREATE TABLE IF NOT EXISTS public.reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id BIGINT REFERENCES public.stations(id) ON DELETE CASCADE NOT NULL,
  user_id UUID DEFAULT auth.uid() NOT NULL,
  status TEXT CHECK (status IN ('working', 'broken', 'occupied')) NOT NULL,
  wait_minutes INTEGER DEFAULT 0,
  note TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. Reservations table (with unique constraint on station_id and slot_start)
CREATE TABLE IF NOT EXISTS public.reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id BIGINT REFERENCES public.stations(id) ON DELETE CASCADE NOT NULL,
  user_id UUID DEFAULT auth.uid() NOT NULL,
  slot_start TIMESTAMPTZ NOT NULL,
  slot_end TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  CONSTRAINT unique_station_slot UNIQUE (station_id, slot_start)
);

-- 4. Pending Stations table for user-submitted chargers awaiting approval
CREATE TABLE IF NOT EXISTS public.pending_stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  address TEXT NOT NULL,
  operator TEXT NOT NULL,
  region TEXT NOT NULL,
  type TEXT NOT NULL,
  price TEXT,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  user_id UUID DEFAULT auth.uid(),
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable Row Level Security (RLS) on all tables
ALTER TABLE public.stations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pending_stations ENABLE ROW LEVEL SECURITY;

-- RLS Policies:

-- Stations: Anyone can read stations
CREATE POLICY "Anyone can read stations" 
ON public.stations 
FOR SELECT 
USING (true);

-- Reports: Anyone can read reports
CREATE POLICY "Anyone can read reports" 
ON public.reports 
FOR SELECT 
USING (true);

-- Reports: Only authenticated users can insert reports for themselves
CREATE POLICY "Authenticated users can insert reports" 
ON public.reports 
FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = user_id);

-- Reports: Users can only edit their own reports
CREATE POLICY "Users can edit their own reports" 
ON public.reports 
FOR UPDATE 
TO authenticated 
USING (auth.uid() = user_id);

-- Reservations: Authenticated users can view reservations
CREATE POLICY "Authenticated users can read reservations" 
ON public.reservations 
FOR SELECT 
TO authenticated 
USING (true);

-- Reservations: Only authenticated users can insert reservations
CREATE POLICY "Authenticated users can insert reservations" 
ON public.reservations 
FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = user_id);

-- Reservations: Users can edit their own reservations
CREATE POLICY "Users can edit their own reservations" 
ON public.reservations 
FOR UPDATE 
TO authenticated 
USING (auth.uid() = user_id);

-- Pending Stations: Authenticated users can insert pending stations
CREATE POLICY "Authenticated users can insert pending stations" 
ON public.pending_stations 
FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = user_id);

-- Pending Stations: Users can read their own submissions
CREATE POLICY "Users can read their own pending stations" 
ON public.pending_stations 
FOR SELECT 
TO authenticated 
USING (auth.uid() = user_id);

-- Pending Stations: Users can edit their own submissions
CREATE POLICY "Users can edit their own pending stations" 
ON public.pending_stations 
FOR UPDATE 
TO authenticated 
USING (auth.uid() = user_id);

-- Enable Realtime replication for reports and reservations
ALTER PUBLICATION supabase_realtime ADD TABLE public.reports;
ALTER PUBLICATION supabase_realtime ADD TABLE public.reservations;

